# Line 2B: the Shunya bridge in BKC (src/components/LeadPictureShunya.astro), the flat drawing the
# 3D scene (src/scripts/three/shunya.ts) replaces. Same geometry: published figures (130 m long,
# 80 m main span, 50 m anchor span, 40 m steel pylon, 12.9 m deck) and the closed "0" of Designfakt's
# renders standing across the line, the deck and a six-car BEML rake through it. Painter's order:
# whatever is east of the loop's west face first, then the loop, then everything west of it.
PX2, LEG2 = 20.0, 3.7
FACE = PX2 - LEG2 / 2          # the loop's visible west face
RO2, RI2, BASE2, H2 = 9.2, 7.0, 2.2, 40.0
YB, YT = BASE2 + RO2, BASE2 + H2 - RO2
D2 = 14.0
TOP2 = D2 + 2.6


def box2(x0, x1, y0, y1, z0, z1, top, front, side, west=True):
    """box() with an optional west face, for a deck cut where it passes through the loop."""
    faces = []
    if west:
        faces.append(poly([(x0, y0, z0), (x0, y1, z0), (x0, y1, z1), (x0, y0, z1)], side))
    faces.append(poly([(x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)], front))
    faces.append(poly([(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)], top))
    return faces


def stadium(r, n=28):
    """Points (y, z) round a stadium of half-width r: over the top, then round the bottom."""
    pts = []
    for i in range(n + 1):
        a = math.pi * i / n
        pts.append((r * math.cos(a), YT + r * math.sin(a)))
    for i in range(n + 1):
        a = math.pi + math.pi * i / n
        pts.append((r * math.cos(a), YB + r * math.sin(a)))
    pts.append(pts[0])
    return pts


def centre_z(z):
    """The centre of the curve a point at height z belongs to (straight sides: the point's own height)."""
    return YT if z > YT else (YB if z < YB else z)


def line2(a, b, stroke, w=0.9):
    (x1, y1), (x2, y2) = P(*a), P(*b)
    return f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{stroke}" stroke-width="{w}" />'


def deck2(x0, x1, west):
    """Box girder, slab, far parapet and median. The near parapet goes on after the train."""
    out = box2(x0, x1, -4.45, 4.45, D2, D2 + 1.2, *CON, west=west)
    out += box2(x0, x1, -6.45, 6.45, D2 + 1.2, D2 + 2.1, *CON, west=west)
    out += box2(x0, x1, -6.45, -6.05, D2 + 2.1, D2 + 3.1, *CON, west=west)
    out += box2(x0, x1, -0.6, 0.6, D2 + 2.1, D2 + 2.6, *CON, west=west)
    return out


def near_parapet(x0, x1, west):
    return box2(x0, x1, 6.05, 6.45, D2 + 2.1, D2 + 3.1, *CON, west=west)


RAKE = ('var(--iso-rake-roof)', 'var(--iso-rake-blue)', 'var(--iso-rake-blue-side)')


def car(x0, x1, lo, hi, head=False):
    """One BEML car on the near track, drawn only between lo and hi along the line."""
    a, b = max(x0, lo), min(x1, hi)
    if a >= b:
        return []
    y0, y1, z0, z1 = 1.8, 5.0, TOP2, TOP2 + 3.7
    out = box2(a, b, y0, y1, z0, z1, *RAKE, west=(a == x0))
    out.append(poly([(a, y1, z0 + 1.55), (b, y1, z0 + 1.55), (b, y1, z0 + 1.72), (a, y1, z0 + 1.72)], 'var(--iso-rake-yellow)'))
    out.append(poly([(a, y1, z0 + 1.85), (b, y1, z0 + 1.85), (b, y1, z0 + 3.2), (a, y1, z0 + 3.2)], 'var(--iso-rake-white)'))
    for wx in (1.6, 6.2, 10.8, 15.4):
        w0, w1 = max(x0 + wx, a), min(x0 + wx + 2.6, b)
        if w0 < w1:
            out.append(poly([(w0, y1, z0 + 2.2), (w1, y1, z0 + 2.2), (w1, y1, z0 + 2.95), (w0, y1, z0 + 2.95)], 'var(--iso-window)'))
    if head and a == x0:
        # The cab front: a white sweep on the west face, with the windscreen in it.
        out.append(poly([(x0, y0, z0 + 1.85), (x0, y1, z0 + 1.85), (x0, y1, z1), (x0, y0, z1)], 'var(--iso-rake-white)'))
        out.append(poly([(x0, y0 + 0.5, z0 + 2.2), (x0, y1 - 0.5, z0 + 2.2), (x0, y1 - 0.5, z0 + 3.2), (x0, y0 + 0.5, z0 + 3.2)], 'var(--iso-window)'))
    return out


def rake(lo, hi):
    """Six cars, the rear cars still west of the loop, the front ones through it and over the nallah."""
    out = []
    starts = [PX2 - 58 + i * 22.9 for i in range(6)][::-1]   # far (east) cars first
    for i, x0 in enumerate(starts):
        out += car(x0, x0 + 22.4, lo, hi, head=(i == 0))
    return out


def cables(side, east):
    """A fan from the loop's inner face to one deck edge: ten into the main span, eight into the anchor span."""
    yA, yD = side * (RI2 + 0.3), side * 6.05
    if east:
        return [line2((PX2 + LEG2 / 2, yA, 24 + i * 1.3), (PX2 + 8 + i * 6.8, yD, TOP2), 'var(--iso-cable)') for i in range(10)]
    return [line2((FACE, yA, 24 + i * 1.6), (PX2 - 7 - i * 5.2, yD, TOP2), 'var(--iso-cable)') for i in range(8)]


def masts(lo, hi):
    out = []
    for x in range(-60, 160, 20):
        if lo <= x < hi and abs(x - PX2) > LEG2 + 3:
            for side in (-1, 1):
                y = side * 5.85
                out.append(line2((x, y, TOP2), (x, y, TOP2 + 7), 'var(--iso-mast)', 1.4))
                out.append(line2((x, y, TOP2 + 6.6), (x, y - side * 3.2, TOP2 + 6.6), 'var(--iso-mast)', 1.1))
    return out


s2 = []
# Ground, then the nallah crossed at a skew: a channel 46 m wide whose west bank meets the line 22 m
# east of the loop, with stone banks. "2B" lies on the west bank.
s2.append(poly([(-200, -200, 0), (300, -200, 0), (300, 200, 0), (-200, 200, 0)], 'var(--iso-ground)'))
TS = math.tan(-0.5)
W0 = PX2 + 22
WX = 46 / math.cos(0.5)


def strip(a, b, fill):
    return poly([(a + TS * -200, -200, 0), (b + TS * -200, -200, 0), (b + TS * 200, 200, 0), (a + TS * 200, 200, 0)], fill)


s2.append(strip(W0 - 3.5, W0, 'var(--iso-stone)'))
s2.append(strip(W0, W0 + WX, 'var(--iso-water)'))
s2.append(strip(W0 + WX, W0 + WX + 3.5, 'var(--iso-stone)'))
for i in range(260):
    yy = -110 + (i * 17.3) % 220
    ln = 1.2 + (i * 7) % 5 * 0.7
    xx = W0 + 2 + (i * 13.7) % (WX - 4) + TS * yy
    s2.append(poly([(xx, yy, 0), (xx + 0.22, yy, 0), (xx + 0.22 + TS * ln, yy + ln, 0), (xx + TS * ln, yy + ln, 0)], 'var(--iso-ripple)'))
s2.append('__TWELVE__')

# Piers west of the loop (the main span's far pier is out of frame), and the plinth under the loop.
for x in (PX2 - 50, PX2 - 80):
    s2 += box(x - 1.6, x + 1.6, -1.6, 1.6, 0, D2 - 1.4, *CON)
    s2 += box(x - 2.6, x + 2.6, -5.45, 5.45, D2 - 1.4, D2, *CON)
s2 += box(PX2 - 4.35, PX2 + 4.35, -6.0, 6.0, 0, BASE2, 'var(--iso-plinth-top)', 'var(--iso-plinth)', 'var(--iso-plinth)')

outer, inner = stadium(RO2), stadium(RI2)
# The inside of the loop where it faces the viewer (its lower and far side), behind the deck.
for (ya, za), (yb, zb) in zip(inner, inner[1:]):
    ym, zm = (ya + yb) / 2, (za + zb) / 2
    if -ym - (zm - centre_z(zm)) > 0:
        s2.append(poly([(FACE, ya, za), (FACE + LEG2, ya, za), (FACE + LEG2, yb, zb), (FACE, yb, zb)], 'var(--iso-pylon-in)'))

# East of the loop's face: deck, far cables, masts, train, near parapet, near cables.
s2 += deck2(FACE, 200, west=False)
s2 += cables(-1, True)
s2 += masts(FACE, 200)
s2 += rake(FACE, 200)
s2 += near_parapet(FACE, 200, west=False)
s2 += cables(1, True)

# The loop: its outer surface where it faces the viewer, then the white west face with its hole.
for (ya, za), (yb, zb) in zip(outer, outer[1:]):
    ym, zm = (ya + yb) / 2, (za + zb) / 2
    if ym + (zm - centre_z(zm)) > 0:
        s2.append(poly([(FACE, ya, za), (FACE + LEG2, ya, za), (FACE + LEG2, yb, zb), (FACE, yb, zb)], 'var(--iso-pylon-rim)'))


